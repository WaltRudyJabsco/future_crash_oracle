#!/usr/bin/env python3
"""Regenerate this checkout's command reference from executable help."""
import argparse
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
COMMANDS = [['future_crash.py', '--help'], ['future_crash_oracle.py', '--help'], ['future_crash_oracle_web.py', '--help'], ['oracle_california85.py', '--help'], ['oracle_sound_system_dub.py', '--help']]
TITLE = 'Future Crash Oracle CLI variants'
MANUAL = False


def outputs():
    sections = []
    with tempfile.TemporaryDirectory(prefix='command-reference-') as home:
        for command in COMMANDS:
            result = subprocess.run([sys.executable, *command], cwd=ROOT, check=True,
                capture_output=True, text=True, timeout=20,
                env=dict(os.environ, HOME=home, USER='demo', LOGNAME='demo', TERM='dumb', NO_COLOR='1', COLUMNS='100'))
            clean = re.sub(r'\x1b\[[0-?]*[ -/]*[@-~]', '', result.stdout).rstrip()
            sections.append((' '.join(command), clean))
    md = ['# ' + TITLE, '', 'Generated by `python3 tools/command_reference.py`; use `--check` to detect drift.', '',
          'Captured from executable help using an isolated home directory.', '']
    for name, text in sections:
        md += ['## ' + name, '', '```text', text, '```', '']
    result = {ROOT / 'docs/CLI.md': '\n'.join(md)}
    if MANUAL:
        def roff(text):
            return '\n'.join((chr(92)+'&' if line.startswith(('.', "'")) else '') + line.replace(chr(92), chr(92)+'e') for line in text.splitlines())
        page = ['.TH LK 1 "" "LOOK ' + (ROOT / 'VERSION').read_text().strip() + '" "User Commands"',
                '.SH NAME', 'lk ' + chr(92) + '- standalone LOOK inspection and command reference',
                '.SH SYNOPSIS', '.B lk [command | path]', '.SH COMMANDS', '.nf']
        page += [roff(text) for _, text in sections]
        page += ['.fi', '.SH SOURCE', 'Generated from root lk help all. The nested look/ directory is a separate older snapshot.']
        result[ROOT / 'lk.1'] = '\n'.join(page) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: raise SystemExit('Regenerate references: ' + ', '.join(stale))
    print(TITLE + ': references synchronized')


if __name__ == '__main__': main()
